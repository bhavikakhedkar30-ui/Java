package Strings;

public class plus {
    static void main(String[] args) {
        String a = "bhavika";
        a +=" khedkar";
        System.out.println(a +10+20); // bhavika1020
        System.out.println(10+20+a); // 30bhavika
        System.out.println(10+a+20);//10bhavika20
        System.out.println('A'+10+a);//ascii value + string
    }
}
